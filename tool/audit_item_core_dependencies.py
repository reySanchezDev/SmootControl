#!/usr/bin/env python3
"""Static dependency inventory for Kivo item-core cutover (F2.0).

Read-only repository scan. Does not connect to any database or execute SQL.
Latest migration definitions win when a routine is redefined.
Produces GitHub Actions artifacts; not an approval of live pg_depend.
"""
from __future__ import annotations

import argparse
import collections
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
MIGRATIONS = ROOT / "supabase" / "migrations"
LEGACY = (
    "products", "packaging_items", "inventory_stock", "inventory_movements",
    "packaging_stock", "packaging_movements", "product_packaging_rules",
)
PATTERN = re.compile(r"\b(" + "|".join(LEGACY) + r")\b", re.I)
FUNCTION = re.compile(
    r"\bCREATE\s+(?:OR\s+REPLACE\s+)?FUNCTION\s+"
    r"(?:public\.)?([a-zA-Z_][\w]*)\s*\(",
    re.I,
)
CREATE_TABLE = re.compile(
    r"\bCREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?"
    r"(?:public\.)?([a-zA-Z_][\w]*)\b",
    re.I,
)
DART_PATHS = (
    ROOT / "lib" / "features",
    ROOT / "lib" / "core" / "database",
)


def scan():
    migrations = sorted(MIGRATIONS.glob("[0-9][0-9][0-9]_*.sql"))
    table_refs = collections.defaultdict(list)
    routines = {}
    for path in migrations:
        content = path.read_text(encoding="utf-8")
        for line_no, line in enumerate(content.splitlines(), 1):
            for table in set(m.group(1).lower() for m in PATTERN.finditer(line)):
                table_refs[table].append((path.relative_to(ROOT).as_posix(), line_no))
        for match in FUNCTION.finditer(content):
            routine = match.group(1).lower()
            # A method name may have overloads; record migration path
            # rather than claim one function signature is definitive.
            routines[routine] = path.relative_to(ROOT).as_posix()
    dart_refs = collections.defaultdict(list)
    for base in DART_PATHS:
        for path in base.rglob("*.dart"):
            content = path.read_text(encoding="utf-8")
            matches = set(m.group(1).lower() for m in PATTERN.finditer(content))
            for table in matches:
                dart_refs[table].append(path.relative_to(ROOT).as_posix())
    return migrations, table_refs, dart_refs, routines


def report(migrations, sql_refs, dart_refs, routines):
    lines = [
        "# F2.0 — Static item-core impact inventory",
        "",
        "> Generated by `tool/audit_item_core_dependencies.py`. "
        "Static text inventory, **not** a database audit; "
        "confirm each object via live `pg_catalog` and `pg_depend`.",
        "",
        f"Migration files scanned: **{len(migrations)}**. "
        f"Last file: `{migrations[-1].name if migrations else 'none'}`.",
        "",
        "| Legacy table | SQL occurrences | Dart files |",
        "|---|---:|---:|",
    ]
    for table in LEGACY:
        lines.append(
            f"| `{table}` | {len(sql_refs[table])} "
            f"| {len(dart_refs[table])} |"
        )
    lines.extend(["", "## Concrete Dart file dependencies", ""])
    for table in LEGACY:
        lines.append(f"### `{table}`")
        matches = sorted(set(dart_refs[table]))
        if not matches:
            lines.append("- None found by literal token (indirect references possible)")
        else:
            lines.extend(f"- `{path}`" for path in matches)
        lines.append("")
    lines.extend(["## SQL occurrence locations", ""])
    for table in LEGACY:
        lines.append(f"### `{table}`")
        locations = sql_refs[table]
        if not locations:
            lines.append("- No literal references detected")
        else:
            lines.extend(
                f"- `{path}:{line_no}`"
                for path, line_no in locations
            )
        lines.append("")
    lines.extend([
        "## Last migration containing each function name",
        "",
        "> Overloads and dynamic SQL require manual signature review.",
        "",
        "| Function | Last containing migration |",
        "|---|---|",
    ])
    for name, path in sorted(routines.items()):
        lines.append(f"| `{name}` | `{path}` |")
    lines.extend(["", "## Scope limits", "",
        "- SQL comments and strings can inflate raw occurrence counts.",
        "- Dynamic references, generated Drift code, triggers and "
        "PostgreSQL dependencies require separate inspection.",
        "- This report never authorizes DROP, migration or deployment.",
    ])
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=pathlib.Path)
    args = parser.parse_args()
    data = scan()
    output = report(*data)
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(output, encoding="utf-8")
        print(f"Created report: {args.output}")
    else:
        print(output)


if __name__ == "__main__":
    main()
